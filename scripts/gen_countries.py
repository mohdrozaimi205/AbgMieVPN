import pycountry, pycountry_convert as pc, sys
from countryinfo import CountryInfo
CONT={'AS':'ASIA','EU':'EUROPE','NA':'NORTH_AMERICA','SA':'SOUTH_AMERICA','AF':'AFRICA','OC':'OCEANIA','AN':'ANTARCTICA'}
over={'AQ':'AN','TL':'AS','EH':'AF','SX':'NA','VA':'EU','PN':'OC','TF':'AN','UM':'OC','BQ':'NA','HM':'AN','BV':'AN','GS':'AN','IO':'AS'}
rows=[]
for c in pycountry.countries:
    a2=c.alpha_2
    try: cc=over.get(a2) or pc.country_alpha2_to_continent_code(a2)
    except Exception: cc=over.get(a2)
    if not cc: print('skip',a2,file=sys.stderr); continue
    name=getattr(c,'common_name',None) or c.name
    cap=''
    try: cap=CountryInfo(a2).capital() or ''
    except Exception: pass
    rows.append((CONT[cc],name,a2,cap))
rows.sort(key=lambda r:(r[0],r[1]))
out=open(sys.argv[1],'w')
out.write('''package com.abgmie.vpn.data.countries

/**
 * Global country database (ISO 3166-1, %d entries) grouped by continent.
 * A country listed here does NOT mean a VPN server exists there.
 * Connectability comes only from servers the owner imports (see ServerRepository).
 * Generated by scripts/gen_countries.py — cities are capital cities (informational).
 */
object CountryData {
    val all: List<Country> = listOf(
''' % len(rows))
def esc(s): return s.replace('\\','\\\\').replace('"','\\"').replace('$','\\$')
for cont,name,a2,cap in rows:
    cities = f'listOf("{esc(cap)}")' if cap else 'emptyList()'
    out.write(f'        Country("{a2}", "{esc(name)}", Continent.{cont}, {cities}),\n')
out.write('''    )
    private val byCode = all.associateBy { it.code }
    fun find(code: String?): Country? = code?.let { byCode[it.uppercase()] }
}
''')
print(len(rows))
