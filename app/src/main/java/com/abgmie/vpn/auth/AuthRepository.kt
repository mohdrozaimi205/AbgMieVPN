package com.abgmie.vpn.auth

import android.content.Context
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.FirebaseApp
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider
import dagger.hilt.android.qualifiers.ApplicationContext
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.tasks.await
import javax.inject.Inject
import javax.inject.Singleton

data class UserProfile(val name: String, val email: String, val photoUrl: String?)

/**
 * Google Sign-In via Credential Manager + Firebase Authentication.
 * Only the Firebase user (name, email, photo URL, UID) is kept by Firebase. Passwords are never seen or stored.
 * Sign-in is optional: without Firebase config the app runs in local-only mode.
 */
@Singleton
class AuthRepository @Inject constructor(@ApplicationContext private val ctx: Context) {

    val firebaseAvailable: Boolean
        get() = runCatching { FirebaseApp.getApps(ctx).isNotEmpty() }.getOrDefault(false) && webClientId() != null

    private val _user = MutableStateFlow(currentUser())
    val user: StateFlow<UserProfile?> = _user.asStateFlow()

    private fun auth(): FirebaseAuth? = if (runCatching { FirebaseApp.getApps(ctx).isNotEmpty() }.getOrDefault(false)) FirebaseAuth.getInstance() else null

    private fun currentUser(): UserProfile? = auth()?.currentUser?.let {
        UserProfile(it.displayName ?: "Google user", it.email ?: "", it.photoUrl?.toString())
    }

    /** default_web_client_id is generated by the google-services plugin when google-services.json exists. */
    private fun webClientId(): String? {
        val id = ctx.resources.getIdentifier("default_web_client_id", "string", ctx.packageName)
        return if (id != 0) ctx.getString(id) else null
    }

    /** @param activityContext must be an Activity context for the Credential Manager UI. */
    suspend fun signIn(activityContext: Context): Result<UserProfile> = runCatching {
        val auth = auth() ?: error("Google Sign-In is not configured yet (see docs/FIREBASE_SETUP.md).")
        val clientId = webClientId() ?: error("Missing default_web_client_id. Add google-services.json and rebuild.")
        val option = GetSignInWithGoogleOption.Builder(clientId).build()
        val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
        val result = CredentialManager.create(activityContext).getCredential(activityContext, request)
        val cred = result.credential
        if (cred !is CustomCredential || cred.type != GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
            error("Unexpected credential type.")
        }
        val google = GoogleIdTokenCredential.createFrom(cred.data)
        auth.signInWithCredential(GoogleAuthProvider.getCredential(google.idToken, null)).await()
        val u = currentUser() ?: error("Sign-in did not complete.")
        _user.value = u
        u
    }

    suspend fun signOut() {
        auth()?.signOut()
        runCatching { CredentialManager.create(ctx).clearCredentialState(ClearCredentialStateRequest()) }
        _user.value = null
    }
}
